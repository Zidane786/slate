    # the v1 file itself is behind a 0.2.0 plugin until migrated
    assert "behind" in seeded.ok("next", "--brief", "--against", str(same)).stdout
    seeded.ok("migrate")
    assert "behind" not in seeded.ok("next", "--brief", "--against", str(same)).stdout


