def fake_plugin(root: Path, version: str) -> Path:
    p = root / f"plugin-{version}"
    (p / ".claude-plugin").mkdir(parents=True)
    (p / ".claude-plugin" / "plugin.json").write_text(json.dumps({"name": "slate", "version": version}))
    return p


def test_version_plain_and_json(seeded: Board) -> None:
    # seeded is a v1 board (0.1.0 / schema 1) read by the v0.2 board.py
    out = seeded.ok("version").stdout.strip()
    assert out == "board 0.2.0 · schema 2 · tickets.json 0.1.0/1"
    j = json.loads(seeded.ok("version", "--json").stdout)
    assert j == {"board": "0.2.0", "schema": 2, "file_slate_version": "0.1.0", "file_schema_version": 1,
                 "plugin": None, "relation": None}


@pytest.mark.parametrize("plugin,relation", [("0.3.0", "behind"), ("0.2.0", "same"), ("0.1.0", "ahead")])
def test_version_against(seeded: Board, plugin: str, relation: str) -> None:
    seeded.ok("migrate")  # bring the v1 fixture to 0.2.0 / schema 2 so "same" is possible
    root = fake_plugin(seeded.root, plugin)
    out = seeded.ok("version", "--against", str(root)).stdout.strip()
    assert out.endswith(f"plugin {plugin} · {relation}")
    j = json.loads(seeded.ok("version", "--against", str(root), "--json").stdout)
    assert j["plugin"] == plugin and j["relation"] == relation


