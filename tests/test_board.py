def git(cwd: Path, *args: str) -> str:
    r = subprocess.run(["git", "-c", "user.name=Test", "-c", "user.email=test@example.com",
                        "-c", "commit.gpgsign=false", *args],
                       cwd=str(cwd), capture_output=True, text=True, check=True)
    return r.stdout.strip()


def git_repo(board: Board, branch: str = "feat/reset") -> str:
    """Make board.root a git repo with one commit; returns the commit's full sha."""
    git(board.root, "init", "-q", "-b", branch)
    (board.root / "app.txt").write_text("hello\n")
    git(board.root, "add", "app.txt")
    git(board.root, "commit", "-q", "-m", "Add the reset page")
