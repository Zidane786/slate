def errors_of(board: Board) -> str:
    r = board.run("check")
    return r.stderr


def check_json(board: Board) -> Dict[str, Any]:
    r = board.run("check", "--json")
    return json.loads(r.stdout)


def assert_error(board: Board, doc: Dict[str, Any], *fragments: str) -> None:
    board.write(doc)
    r = board.run("check")
    assert r.returncode == 1, r.stdout + r.stderr
    for f in fragments:
        assert f in r.stderr, f"{f!r} not in:\n{r.stderr}"


