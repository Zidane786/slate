    assert "Needs: ACME-001 (backlog)" in out
    assert "docs/plans/2026-09-26-reset.md" in out
    assert "2026-09-26 · review: Built the form." in out
    assert all(len(l) <= 80 for l in out.splitlines() if "──" not in l), out
    j = json.loads(seeded.ok("show", "ACME-004", "--json").stdout)
    assert j["id"] == "ACME-004" and j["user_checks"]["0"]["result"] == "pass"


