    doc = seeded.load()
    doc["tickets"].append(rich_ticket())
    seeded.write(doc)
    seeded.ok("check")
    out = seeded.ok("show", "ACME-004").stdout
    order = ["Summary", "Story", "Picture", "Done when", "Try it yourself", "Automated tests", "Details",
             "Technical notes", "Needs / unlocks", "Plan doc", "History"]
    pos = [out.index("\n" + h + "\n") for h in order]
    assert pos == sorted(pos), out
    assert out.startswith("ACME-004 · People can reset a forgotten password\n")
    assert "Phase P1 (Link arrives)" in out
    assert "      1. Click 'Forgot password'" in out and "      3. Click 'Send link'" in out
    assert "Test 1 (required): Reset with a known email" in out
    assert "Result: pass on 2026-09-26 (looked fine)" in out
